// ── Types ───────────────────────────────────────────────────────────────

export interface UserOption { id: string; name: string; email: string }
export interface ModuleOption { id: number; moduleName: string; projectId: number }
export interface ExistingProjectOption {
  id: number
  projectName: string
  projectCode: string
  clientId: string
  clientName: string | null
  clientEmail: string | null
}
export interface FormErrors { [key: string]: string }

export type WizardStep = 1 | 2 | 3 | 4 | 'review' | 'success'

export type OnboardingMode = 'new' | 'existing'

export interface ClientUserEntry {
  tempId: string
  firstName: string
  lastName: string
  email: string
  phoneNumber: string
  /** ISO-3166 alpha-2 country code for the phone number. */
  countryCode: string
  designation: string
  userType: ClientUserType
  password: string
  isAutoGenerated: boolean
  sendEmail: boolean
}

export interface OnboardingState {
  step: WizardStep
  mode: OnboardingMode
  submitting: boolean
  errors: FormErrors
  onboardingResult: OnboardingResult | null

  // Lookup data (loaded lazily per step)
  managerList: UserOption[]
  existingModules: ModuleOption[]
  availableProjects: ExistingProjectOption[]

  // Project
  projectName: string
  selectedManager: string
  selectedProjectId: number | null
  projectDescription: string
  projectStartDate: string
  projectEndDate: string
  projectType: string
  projectPriority: string
  projectNotes: string

  // Modules
  newModules: { name: string; description: string }[]
  selectedExistingModules: number[]
  moduleSearch: string
  // Existing project mode — project's modules + new modules to create
  projectModules: ModuleOption[]
  loadingProjectModules: boolean
  existingModeNewModules: { name: string; description: string }[]

  // Client Users (multiple)
  clientUsers: ClientUserEntry[]
  editingUserTempId: string | null  // null = adding new, non-null = editing existing

  // Form fields for the user being added/edited
  userFormFirstName: string
  userFormLastName: string
  userFormEmail: string
  userFormPhoneNumber: string
  userFormCountryCode: string
  userFormDesignation: string
  userFormUserType: ClientUserType
  userFormPassword: string
  userFormUseManualPassword: boolean
  userFormShowPassword: boolean
  userFormSendEmail: boolean

  // Support Contract
  contractType: ContractType | ''
  hypercareDuration: HypercareDuration | ''
  supportHours: string
  supportStartDate: string
  supportEndDate: string
  supportRemarks: string

  // Notification Preferences
  enableTeamsNotifications: boolean
}

type Action =
  | { type: 'SET_STEP'; step: WizardStep }
  | { type: 'SET_SUBMITTING'; submitting: boolean }
  | { type: 'SET_ERRORS'; errors: FormErrors }
  | { type: 'CLEAR_ERRORS' }
  | { type: 'SET_ONBOARDING_RESULT'; result: OnboardingResult | null }
  | { type: 'SET_MANAGERS'; managers: UserOption[] }
  | { type: 'SET_MODULES'; modules: ModuleOption[] }
  | { type: 'SET_EXISTING_PROJECTS'; projects: ExistingProjectOption[] }
  | { type: 'SET_FIELD'; field: string; value: any }
  | { type: 'SET_NEW_MODULES'; modules: { name: string; description: string }[] }
  | { type: 'SET_SELECTED_EXISTING_MODULES'; ids: number[] }
  | { type: 'ADD_MODULE' }
  | { type: 'REMOVE_MODULE'; index: number }
  | { type: 'UPDATE_MODULE'; index: number; field: string; value: string }
  | { type: 'TOGGLE_EXISTING_MODULE'; id: number }
  | { type: 'LOAD_DRAFT'; data: OnboardingFormData }
  // User management actions
  | { type: 'ADD_USER'; user: ClientUserEntry }
  | { type: 'REMOVE_USER'; tempId: string }
  | { type: 'UPDATE_USER'; tempId: string; user: ClientUserEntry }
  | { type: 'SET_EDITING_USER'; tempId: string | null }
  | { type: 'SET_USER_FORM_FIELD'; field: string; value: any }
  | { type: 'RESET_USER_FORM' }

function calculateHypercareEndDate(startDate: string, durationDays: number): string {
  if (!startDate || !durationDays) return ''
  const start = new Date(startDate)
  start.setDate(start.getDate() + durationDays)
  return start.toISOString().split('T')[0]
}

let tempIdCounter = 0
function generateTempId(): string {
  return `user_${++tempIdCounter}_${Date.now()}`
}

